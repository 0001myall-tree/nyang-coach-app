/// 마스터 코치(여비서/냥할배) 자동 발화의 문구와 조립 규칙.
///
/// 채팅 화면에서 떼어낸 이유는 검증이다. 화면 안에 있으면 앱을 띄우고 로그인해서
/// 해당 시간대가 되기를 기다려야 발화 한 줄을 볼 수 있었다. 여기 있는 것은 위젯도
/// prefs도 모르고, 넘겨받은 [MasterGreetingContext] 하나로만 판단하므로 테스트에서
/// 모든 분기를 지어 넣고 나오는 문장을 눈으로 훑을 수 있다.
///
/// 화면에 남는 몫: 상태를 읽어 컨텍스트를 만드는 일, 하루 1회 가드, 실제 발화.

/// 마스터 코치 자동 발화의 시간 슬롯. 발화 예산은 슬롯당 하루 1회다.
/// 시각·계획·완료 상태는 "무슨 말을 할지"만 고르고 "몇 번 말할지"는 늘리지 않는다.
enum GreetingSlot { dawn, day, evening }

class MasterGreetingContext {
  final DateTime now;
  final int? daysSinceLastVisit;

  /// 습관을 뺀 오늘 일정. 자정 리셋이 습관을 자동으로 넣어주기 때문에,
  /// 습관까지 세면 "계획 없음" 분기가 영영 안 걸린다.
  final int planTotal;
  final int planDone;

  /// 오늘 몫인 습관. 완료율에는 이쪽도 넣는다 — 습관도 세워둔 계획이라,
  /// 일정만 끝내고 습관이 통째로 남았는데 "전부 마치셨습니다"라고 할 수 없다.
  /// 계획 유무는 위 [planTotal]로만 보므로 "계획 없음" 분기는 그대로 걸린다.
  final int habitTotal;
  final int habitDone;

  /// 격려 기준이 되는 완료 개수(습관 포함). 완료율이 아니라 개수를 쓰는 이유도
  /// 같다 — 자동 주입된 습관이 분모를 오염시킨다.
  final int doneCount;

  /// 오늘 일정/습관 중 시작 또는 완료 흔적이 있는 개수.
  final int startedCount;

  /// 격려에 녹일 완료 항목 이름. 제목이 길거나 완료가 없으면 null.
  final String? doneLabel;

  /// 저녁 선택 카드에 띄울 미완료 일정/습관.
  final List<String> pendingPlans;

  /// 어젯밤 늦게까지(새벽 2~6시) 앱을 쓴 흔적이 있는지.
  final bool lateNight;

  /// 최근에 늦은 밤 앱/플래너 진입이 여러 날 반복됐는지.
  final bool repeatedLateNights;

  /// 어제나 오늘 아프다고 말한 적이 있는지.
  final bool feltSick;

  /// 오늘 하기 싫다고 말했던 일정을 끝내 완료했는지.
  final bool resistedDone;

  /// 그 일정 이름. 제목이 길면 null이고, 이름 없이 격려만 한다.
  final String? resistedDoneLabel;

  /// 오늘 하기 싫다고 했던 일정이 아직 완료 전이지만 진행 중 표시가 되어 있는지.
  final bool resistedInProgress;

  /// 그 일정 이름. 제목이 길면 null이고, 이름 없이 응원만 한다.
  final String? resistedInProgressLabel;

  /// 오늘 하기 싫다고 했던 일정이 계획에 남아 있고 아직 시작 표시도 없는지.
  final bool resistedNotStarted;

  /// 그 일정 이름. 제목이 길면 null이고, 이름 없이 묻는다.
  final String? resistedNotStartedLabel;

  /// 오늘 하기 싫다고 한 게 계획에 없는 일이라, 했는지 안 했는지 알 길이 없는지.
  /// 이때만 코치가 직접 물어본다 — 기록으로는 영영 알 수 없는 자리다.
  final bool offPlanResistance;

  /// 첫 일정을 잡았을 때 그날이 잘 풀린 시간대("오전 8시~10시").
  ///
  /// 값이 있으면 오전(7~12시) 인사를 이 이야기로 바꾼다. 채워 넣을지는 화면이
  /// 정한다 — 주 1회 제한과 기록이 충분한지가 여기서는 보이지 않는다.
  final String? startPatternLabel;

  /// 곧 시작하기로 해둔 일정의 이름과 시각("오후 3시 30분").
  ///
  /// 시작 시각이 적혀 있고 한 시간 안쪽으로 남았을 때만 채워진다. 이때
  /// "가벼운 것부터 하나 열어보시죠"는 어긋난다 — 할 일도 시각도 이미 정해져
  /// 있는 사람에게 다른 걸 고르라는 말이 되기 때문이다.
  final String? upcomingPlanName;
  final String? upcomingPlanTimeLabel;

  const MasterGreetingContext({
    required this.now,
    required this.daysSinceLastVisit,
    required this.planTotal,
    required this.planDone,
    this.habitTotal = 0,
    this.habitDone = 0,
    required this.doneCount,
    this.startedCount = 0,
    required this.doneLabel,
    required this.pendingPlans,
    required this.lateNight,
    this.repeatedLateNights = false,
    required this.feltSick,
    this.resistedDone = false,
    this.resistedDoneLabel,
    this.resistedInProgress = false,
    this.resistedInProgressLabel,
    this.resistedNotStarted = false,
    this.resistedNotStartedLabel,
    this.offPlanResistance = false,
    this.startPatternLabel,
    this.upcomingPlanName,
    this.upcomingPlanTimeLabel,
  });

  bool get hasPlan => planTotal > 0;

  /// 밤 9시대인데 아직 남은 일정이 둘 이상인 상태.
  ///
  /// 이 시간에 다 하라는 말은 뜻이 없다. 계획을 좁히자고 말할 자리다.
  /// 이미 절반을 넘겼으면 좁힐 것이 별로 없으니 원래 흐름대로 둔다.
  bool get needsMinimumBar =>
      now.hour >= MasterGreetingCopy.minimumBarFromHour &&
      now.hour < quietFromHour &&
      pendingPlans.length >= MasterGreetingCopy.minimumBarPendingCount &&
      planRate <= 0.5;

  /// 저녁 8시 이후인데 오늘 아직 시작한 흔적이 하나도 없는 상태.
  bool get needsEveningMinimumSuccessReset =>
      now.hour >= MasterGreetingCopy.eveningNoStartFromHour &&
      now.hour < quietFromHour &&
      hasPlan &&
      planDone == 0 &&
      habitDone == 0 &&
      doneCount == 0 &&
      startedCount == 0;

  /// 아직 아무것도 못 했는데, 곧 시작하기로 해둔 일정이 있는 상태.
  bool get hasUpcomingPlan =>
      doneCount == 0 &&
      upcomingPlanName != null &&
      upcomingPlanTimeLabel != null;

  /// 완료율. 일정과 습관을 함께 센다.
  double get planRate {
    final total = planTotal + habitTotal;
    return total == 0 ? 0 : (planDone + habitDone) / total;
  }

  bool get isComeback => daysSinceLastVisit != null && daysSinceLastVisit! >= 2;

  /// 이 시각부터는 아무 말도 하지 않는다.
  ///
  /// 저녁 인사는 하루를 정리하는 말이라 이 시간엔 늦었고, 그렇다고 재우는 말을
  /// 하기도 어렵다 — 늦게 자는 사람에게는 참견이 된다. 자정을 넘겨 들어오면
  /// 그때는 새벽 문구가 받는다.
  static const quietFromHour = 23;

  bool get isQuietHour => now.hour >= quietFromHour;

  GreetingSlot get slot {
    if (now.hour < 7) return GreetingSlot.dawn;
    if (now.hour < 18) return GreetingSlot.day;
    return GreetingSlot.evening;
  }
}

class MasterGreetingResult {
  final String text;

  /// 비어 있지 않으면 저녁 ≤50% 선택 카드를 띄운다.
  final List<String> choices;

  /// 시작 패턴 이야기를 실제로 꺼냈는지. 컨텍스트에 패턴이 실려 있어도 컨디션
  /// 문구처럼 앞서는 자리가 있어서, 화면은 이 값을 보고 주 1회를 센다.
  final bool usedStartPattern;

  const MasterGreetingResult(
    this.text, {
    this.choices = const [],
    this.usedStartPattern = false,
  });
}

/// 코치 한 명의 발화 문구 한 벌.
class GreetingVoice {
  final List<String> dawn; // 00~05시: 아직 안 잔 사람
  final List<String> earlyMorning; // 05~07시: 일찍 일어난 사람
  final List<String> earlyStart; // 07~09시: 계획 유무를 따지지 않는 시작 인사
  final List<String> earlyQuestions;
  // 9시 뒤 낮 문구는 한 문장으로 끝나므로 제안이나 질문을 문장 안에 품는다.
  // 질문만 홀로 던지면 부담이 되니, 부담을 코치가 가져간다는 말과 한 세트로 둔다.
  final List<String> morningPlan; // 09~12시, 계획 있음
  final List<String> morningNoPlan;

  /// 주 1회만 나가는 오전 인사. `{{window}}`는 "오전 8시~10시" 같은 구간 이름.
  ///
  /// 다른 오전 문구가 오늘 뭘 할지 묻는 자리라면 여기는 지금까지의 기록에서
  /// 보인 리듬을 한 번 알려주고 물러나는 자리다. 그래서 이 틀만 세 줄이다.
  ///
  /// 단정하지 않는다. 사흘치로도 나갈 수 있고, "그 시간에 시작해야 한다"는
  /// 지시로 읽히면 그 시간을 놓친 날마다 하루가 이미 망한 것이 된다.
  final List<String> startPatternMorning;
  final List<String> afternoonBehind; // 12~18시, 계획은 있는데 아직 완료 0
  final List<String> afternoonNoPlan;

  /// 시각까지 정해둔 일정이 한 시간 안쪽으로 다가온 자리. `{{time}}`은
  /// "오후 3시 30분", `{{task}}`는 일정 이름.
  ///
  /// 다른 낮 문구가 "뭐부터 잡아볼까요"라면 여기는 이미 정해진 것을 확인해주고
  /// 물러나는 자리다. 시작을 재촉하지 않는다 — 아직 시각이 오지 않았으니
  /// 지금 쉬는 게 맞고, 코치는 그래도 된다고만 말한다.
  ///
  /// 준비 이야기는 오히려 이 자리의 목적이다. 어디서 어떻게 할지가 그려져 있으면
  /// 그 시각에 실제로 몸이 움직인다. 다만 그 말로 문장을 끝내면 숙제가 되므로,
  /// 준비는 가운데 두고 문장은 반드시 쉬어도 된다는 말로 맺는다.
  final List<String> upcomingPlan;
  final List<String> eveningLow; // 완료 50% 이하
  final List<String> eveningMid; // 51~80%
  final List<String> eveningHigh; // 81~99%
  // 저녁 초입(18~20시)은 낮인지 저녁인지 헷갈리는 시간이라 마무리 인사가 이르다.
  // 이 두 자리에서만 하루가 아직 열려 있다는 쪽으로 말한다.
  final List<String> earlyEveningNone; // 저녁 초입, 완료 0
  final List<String> earlyEveningHigh; // 저녁 초입, 81~99%
  final List<String> eveningNoStartMinimum; // 20시 이후, 시작 기록 0

  /// 밤 9시대, 아직 남은 일정이 둘 이상일 때.
  ///
  /// 이 시간에 남은 것을 다 하라는 말은 아무 쓸모가 없다. 대신 계획을 고쳐
  /// 잡게 돕는다.
  ///
  /// 남은 것 중 하나만 하라는 말이 아니다. 그 하나를 오늘 할 수 있는 크기로
  /// 줄여 다시 적자는 말이다 — '1화 쓰기'를 '1화 개요만 쓰기'로. 할 일을 고르는
  /// 게 아니라 할 일의 크기를 고치는 자리이고, 그래야 이상적으로 짜둔 하루가
  /// 실패로 끝나지 않는다.
  ///
  /// 예시는 사용자의 일정 이름이 아니라 고정된 한 쌍으로 둔다. 줄인다는 게 어떤
  /// 모양인지는 전후를 나란히 보여줘야 잡히는데, 남의 일정 이름만 불러서는
  /// 줄인 뒤가 없어 감이 오지 않는다.
  ///
  /// "이렇게 하자"가 아니라 "이렇게 하면 어때?"로 묻는다. 계획을 고치는 건
  /// 사용자 몫이라, 코치가 정해주면 그것대로 또 하나의 지시가 된다.
  ///
  /// 반드시 '최소'라고 말한다. 그냥 '성공 기준'이라고 하면 기준을 낮춘 것이
  /// 되어, 이렇게 계속 타협하다 영영 밀리는 것 아닌가 하는 걱정을 부른다.
  ///
  /// 다만 한 발화에서 '최소 성공'을 두 번 말하지는 않는다. 안심시킬 자리에서는
  /// 그 말을 되풀이하는 대신 성공이 무엇인지를 다시 말한다 — 다 해내는 것이
  /// 아니라 중요한 일에 할 수 있을 만큼 집중하는 것이라고.
  final List<String> eveningMinimumBar;
  final List<String> eveningAll; // 100%
  final List<String> eveningNoPlan;
  final List<String> comeback; // 2일 이상 만에 돌아왔을 때 앞에 붙일 한 문장

  /// 복귀한 날 뒤에 붙일 문장. 뭘 했고 뭐가 남았는지 짚는 대신 도움을 청하라고만 한다.
  final List<String> comebackSupport;
  final List<String> afterLateNight; // 늦게 잔 다음 날 낮
  final List<String> afterRepeatedLateNights; // 늦은 밤 패턴이 5일 이상 반복된 다음 날 낮
  final List<String> afterSick; // 아프다고 한 다음 날 낮

  /// 격려 문구. (완료 항목 이름을 넣는 형태, 이름 없이 쓰는 형태) 순서다.
  final List<(String, String)> encStarted; // 오전 1~2개 완료
  final List<(String, String)> encStrong; // 오전 3개 이상 완료
  final List<(String, String)> encFlow; // 오후 절반 이상 완료
  final List<(String, String)> encEvening; // 저녁 발화용

  /// 하기 싫다던 일을 끝낸 날 저녁. 해낸 것을 짚고, 다음에도 도와주겠다고 한다.
  /// 다른 저녁 문구와 달리 이 자체로 두 문장이라 뒤에 격려를 붙이지 않는다.
  final List<(String, String)> eveningResistedDone;

  /// 하기 싫다던 일이 진행 중 표시로 남아 있을 때. 이미 시작한 흐름을 끊지 않는다.
  final List<(String, String)> eveningResistedInProgress;

  /// 하기 싫다던 일이 아직 시작 표시도 없을 때. 비난하지 않고 시작 표시만 권한다.
  final List<(String, String)> eveningResistedNotStarted;

  /// 계획에 없어 확인할 길이 없는 일을 물어보는 자리. 이름을 부르지 않는다 —
  /// 자유 문장에서 일 이름만 뽑아낼 방법이 없고, 잘못 부르면 딴 일을 묻게 된다.
  final List<String> eveningOffPlanAsk;

  /// 그 일을 했다고 답했을 때. 코치가 자기 기분을 말한다.
  final List<String> offPlanDoneReply;

  /// 핵심으로 잡아둔 일에 시작 표시가 없을 때 물어보는 말. `{{task}}`는 일정 이름.
  ///
  /// 표시가 없다고 안 한 것으로 단정하지 않는다 — 이미 했는데 누르는 걸 잊었을
  /// 수 있다. 그래서 묻되, 왜 묻는지(표시가 비어 있다는 것)를 밝힌다.
  final List<String> coreAsk;

  /// 하는 날과 안 하는 날이 갈리는 사람에게, 무엇이 달랐는지 묻는 말.
  ///
  /// 못 한 날을 나무라지 않는다. 하는 날에는 잡은 것을 다 해내는 사람이라
  /// 양이나 구체성이 걸린 것이 아니다. 걸린 것은 시작 여부이고, 그건 앱이
  /// 기록으로는 못 보는 자리다.
  final List<String> conditionAsk;

  /// 답을 골랐을 때. 알아들었다는 것만 짧게 알린다.
  final List<String> conditionReply;

  /// 오늘 쓸 수 있는 시간을 묻는 말.
  ///
  /// 계획을 짜기 전에 묻는다. 개수로만 재던 때는 두 시간뿐인 날의 다섯 개와
  /// 온종일 비는 날의 다섯 개가 같은 것이 되었다.
  final List<String> capacityAsk;

  /// 답을 골랐을 때. 여기서 계획을 줄이라고 하지 않는다 — 아직 오늘 계획이
  /// 무엇인지도 모르는 자리다.
  final List<String> capacityReplyTight;
  final List<String> capacityReplyRoomy;

  /// 막혀 있다고 한 뒤, 무엇이 걸리는지 묻는 말.
  ///
  /// 코치가 답을 이미 한 뒤에 붙는 카드라 짧아야 한다. 위로를 또 하지 않는다.
  final List<String> blockerAsk;

  /// 목록에 없다고 했을 때, 그 자리에서 적어달라고 청하는 말.
  final List<String> blockerFreeAsk;

  /// 무엇이 막는지 골랐을 때. 고쳐주겠다고 나서지 않는다 — 지금은 알아둔
  /// 것으로 충분하고, 무엇을 할지는 다음 대화에서 그 답을 보고 정한다.
  final List<String> blockerReply;


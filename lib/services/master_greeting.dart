  ///
  /// 늘었다는 말을 먼저 한다. 이 사람에게는 완료율이 눈금이 못 되어서,
  /// 나아지고 있다는 것을 볼 수 있는 자리가 여기뿐이다.
  final List<String> conditionAskImproved;

  /// 목록에 없는 답이라고 했을 때. 그 자리에서 적어달라고 청한다.
  final List<String> conditionFreeAsk;

  /// 권한 대로 해내고 온 날 아침에 건네는 말. `{{task}}`가 그 일,
  /// `{{advice}}`는 그때 무엇을 권했는지.
  ///
  /// 오늘 무엇을 하라는 말은 붙이지 않는다. 챙겨주는 자리지 시키는 자리가
  /// 아니다. 그리고 내 말 덕이라고 하지 않는다 — 다른 코치가 건넨 말일 수도
  /// 있고, 무엇보다 해낸 것은 사용자다.
  final List<String> adviceWorked;

  /// 며칠째 못 끝내고 넘어온 일을 묻는 말. `{{task}}`가 그 일, `{{days}}`는
  /// 며칠째인지.
  ///
  /// 나무라지 않는다는 말은 하지 않는다. 그 말을 꺼내는 순간 나무랄 일이라는
  /// 뜻이 되어서, 안 하려던 지적을 대신 해버린다. 그냥 사실을 적고 무엇이
  /// 걸렸는지를 묻는다 — 며칠 걸려 있는 일에 필요한 것은 조언이 아니라
  /// 어디가 막혔는지다.
  final List<String> carriedAsk;

  /// 핵심도 습관도 아닌, 오늘 적어둔 나머지 일 하나를 묻는 말.
  ///
  /// 왜 하필 이 일인지 밝힌다 — 오늘 목록에 남아 있다는 것. 그게 여기서 댈
  /// 수 있는 유일한 근거이자, 사실인 유일한 근거다. 자주 하던 일이라고
  /// 말하던 때는 목록에 적어두기만 하고 못 한 일에도 그렇게 말했다.
  final List<String> repeatingAsk;

  /// 시작은 했다고 답했을 때. 마스터 코치는 표시를 대신 켜주고 그 사실을 알린다.
  final List<String> coreAskStartedReply;

  /// 이미 표시가 켜져 있어 대신 켤 것이 없었을 때.
  final List<String> coreAskAlreadyReply;

  /// 상황 때문에 못 했다고 답했을 때. 다음 행동을 밀지 않는다.
  final List<String> coreAskBusyReply;

  /// 며칠째 넘어온 일을 두고 "시간이 없었다"고 답했을 때.
  ///
  /// 여기서는 물러나지 않는다. 하루 못 한 것과 며칠째 밀린 것은 다르다.
  /// 시간이 없어서였다면 막힌 곳이 분명하니, 오늘은 그 자리를 먼저 잡는다.
  final List<String> carriedBusyReply;

  /// 시작해두고 한참 지나도록 완료가 안 된 일을 저녁에 물어보는 말.
  /// `{{task}}`는 일정 이름.
  ///
  /// 멈췄다고 단정하지 않는다 — 아직 붙잡고 있을 수도, 끝내놓고 누르는 걸
  /// 잊었을 수도 있다. 그래서 상태를 묻되 답하기 편한 쪽으로 연다.
  final List<String> stalledAsk;

  /// 지금 붙잡고 있는 일을 인정하는 말. `{{task}}`가 그 일, `{{next}}`는
  /// 아직 손대지 않은 다음 일이다.
  ///
  /// 낮에 진행 중인 사람에게 다른 일을 들이밀면 그게 방해다. 그렇다고 아무
  /// 말도 안 하면 하고 있는 걸 못 본 셈이 된다. 인정하고, 다음 것 하나만
  /// 남겨두고 물러난다.
  final List<String> inProgressAck;

  /// 다음에 볼 것이 없을 때. 남겨둘 것이 없으면 인정만 하고 끝낸다.
  final List<String> inProgressAckOnly;

  /// 붙잡고 있은 시간까지 말할 때. `{{spent}}`가 그 시간이다.
  ///
  /// 얼마나 했는지를 말해주면 인정이 구체적이 된다. 다만 짧게 하고 있을 때는
  /// 쓰지 않는다 — 5분 하고 "5분이나 하셨네요"는 놀리는 말이 된다.
  final List<String> inProgressAckSpent;

  /// 시간은 말하되 다음에 볼 것이 없을 때.
  final List<String> inProgressAckSpentOnly;

  /// 완료를 누르는 걸 잊었다고 답했을 때. 코치가 대신 완료로 바꿔준다.
  final List<String> stalledDoneReply;

  /// 대신 바꿔줄 것이 없었을 때(이미 완료로 되어 있음).
  final List<String> stalledAlreadyDoneReply;

  /// 상황 때문에 멈췄다고 답했을 때.

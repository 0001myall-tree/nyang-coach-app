  final GreetingVoice voice;

  MasterGreetingBuilder({required this.voice, super.recentLines, super.random});

  /// 한 발화는 최대 2문장(복귀 인사가 붙으면 그 앞에 한 문장 더).
  MasterGreetingResult build(MasterGreetingContext context) {
    // 늦은 밤은 비운다. 빈 문장을 돌려주면 화면이 발화를 건너뛴다.
    // 오래 비웠다 돌아온 날만 예외다. 그건 하루를 관리하는 말이 아니라
    // 반가움이라, 늦은 시간에도 하는 편이 낫다.
    if (context.isQuietHour && !context.isComeback) {
      return const MasterGreetingResult('');
    }

    final hour = context.now.hour;
    final parts = <String>[];
    if (context.isComeback) {
      parts.add(pickLine(voice.comeback));
      // 오래 비웠다 돌아온 날은 뭘 했고 뭐가 남았는지 짚지 않는다. 뭉뚱그려
      // 도움을 청하라고만 하고 끝낸다. 새벽 문구는 원래 계획을 안 짚으니 그대로 둔다.
      if (context.slot != GreetingSlot.dawn) {
        parts.add(pickLine(voice.comebackSupport));
        return MasterGreetingResult(parts.join(' '));
      }
    }

    switch (context.slot) {
      case GreetingSlot.dawn:
        // 같은 새벽이라도 5시 전은 아직 안 잔 쪽, 그 뒤는 일찍 일어난 쪽으로 본다.
        parts.add(pickLine(hour < 5 ? voice.dawn : voice.earlyMorning));
        return MasterGreetingResult(parts.join(' '));

      case GreetingSlot.day:
        // 어제 아팠거나 늦게 잔 날은 계획 이야기보다 컨디션을 먼저 챙긴다.
        if (context.feltSick ||
            context.repeatedLateNights ||
            context.lateNight) {
          parts.add(
            pickLine(
              context.feltSick
                  ? voice.afterSick
                  : context.repeatedLateNights
                  ? voice.afterRepeatedLateNights
                  : voice.afterLateNight,
            ),
          );
          return MasterGreetingResult(parts.join(' '));
        }
        // 주 1회 자리. 오늘 뭘 할지 묻는 대신 내 리듬을 한 번 짚어준다.
        // 컨디션보다는 뒤에 둔다 — 아픈 날 아침에 완료율 이야기를 꺼낼 수는 없다.
        final startPattern = context.startPatternLabel;
        if (startPattern != null && hour < 12) {
          parts.add(_fillWindow(voice.startPatternMorning, startPattern));
          return MasterGreetingResult(parts.join(' '), usedStartPattern: true);
        }
        // 시각까지 정해둔 일정이 곧 시작한다면 그게 오늘의 이야기다. 다른 걸
        // 고르라고 하면 이미 정해둔 사람에게 딴 데를 가리키는 말이 된다.
        if (context.hasUpcomingPlan) {
          parts.add(_fillUpcoming(context));
          return MasterGreetingResult(parts.join(' '));
        }
        if (hour < 9) {
          // 9시 전에는 계획 유무를 따지지 않고 하루를 여는 인사만 한다.
          final encouragement = _dayEncouragement(context);
          parts.add(pickLine(voice.earlyStart));
          parts.add(
            encouragement.isNotEmpty
                ? encouragement
                : pickLine(voice.earlyQuestions),
          );
          return MasterGreetingResult(parts.join(' '));
        }
        parts.add(_dayLine(context));
        return MasterGreetingResult(parts.join(' '));

      case GreetingSlot.evening:
        // 하기 싫다던 일을 끝낸 날은 그게 오늘의 이야기다. 완료율이 낮아도
        // 뭐가 걸렸는지 되묻지 않고(선택 카드도 띄우지 않고) 해낸 것만 짚는다.
        // 문구가 이미 도움을 청하라는 말로 끝나므로 카드가 하던 몫도 겸한다.
        if (context.resistedDone) {
          final praise = pickEncouragement(
            voice.eveningResistedDone,
            context.resistedDoneLabel,
          );
          if (praise.isNotEmpty) {
            parts.add(praise);
            return MasterGreetingResult(parts.join(' '));
          }
        }
        if (context.resistedInProgress) {
          parts.add(
            pickEncouragement(
              voice.eveningResistedInProgress,
              context.resistedInProgressLabel,
            ),
          );
          return MasterGreetingResult(parts.join(' '));
        }
        if (context.resistedNotStarted) {
          parts.add(
            pickEncouragement(
              voice.eveningResistedNotStarted,
              context.resistedNotStartedLabel,
            ),
          );
          return MasterGreetingResult(parts.join(' '));
        }
        // 계획에 없는 일이라 기록으로는 영영 알 수 없다. 코치가 직접 묻고,
        // '아직'이면 실행 저항 흐름을 한 번 더 태운다.
        if (context.offPlanResistance) {
          parts.add(pickLine(voice.eveningOffPlanAsk));
          return MasterGreetingResult(
            parts.join(' '),
            choices: const [
              MasterGreetingCopy.offPlanDoneLabel,
              MasterGreetingCopy.offPlanNotYetLabel,
            ],
          );
        }
        if (!context.hasPlan) {
          parts.add(pickLine(voice.eveningNoPlan));
          return MasterGreetingResult(parts.join(' '));
        }
        // 저녁에도 시각을 정해둔 일정이 곧 시작할 수 있다. 그때는 하루를 접는
        // 말보다 그 일정을 짚어주는 편이 맞다.
        if (context.hasUpcomingPlan) {
          parts.add(_fillUpcoming(context));
          return MasterGreetingResult(parts.join(' '));
        }
        if (context.needsEveningMinimumSuccessReset) {
          parts.add(pickLine(voice.eveningNoStartMinimum));
          return MasterGreetingResult(parts.join(' '));
        }
        // 밤 9시대에 남은 게 둘 이상이면, 뭐가 미뤄졌는지 되묻는 대신
        // 오늘의 기준을 스스로 좁히도록 돕는다.
        if (context.needsMinimumBar) {
          parts.add(pickLine(voice.eveningMinimumBar));
          return MasterGreetingResult(parts.join(' '));
        }
        final rate = context.planRate;
        // 18~20시는 낮인지 저녁인지 헷갈리는 시간이라 하루를 아직 접지 않는다.
        final isEarlyEvening = hour < MasterGreetingCopy.earlyEveningUntilHour;
        if (rate <= 0.5) {
          // 귀찮았던 일을 버튼으로 고르게 하고, 고른 일은 실행 저항 흐름으로 넘긴다.
          // 다만 아직 하나도 못 한 저녁 초입에는 뭐가 걸렸는지 묻는 대신
          // 지금 시작해도 늦지 않았다고 말한다.
          parts.add(
            pickLine(
              // 습관이라도 하나 했으면 "아직 아무것도 안 했다"가 아니다.
              isEarlyEvening && context.doneCount == 0
                  ? voice.earlyEveningNone
                  : voice.eveningLow,
            ),
          );
          return MasterGreetingResult(
            parts.join(' '),
            choices: eveningChoices(context.pendingPlans),
          );
        }
        if (rate >= 1.0) {
          parts.add(pickLine(voice.eveningAll));
        } else if (rate > 0.8) {
          parts.add(
            pickLine(
              isEarlyEvening ? voice.earlyEveningHigh : voice.eveningHigh,
            ),
          );
        } else {
          parts.add(pickLine(voice.eveningMid));
        }
        final encouragement = pickEncouragement(
          voice.encEvening,
          context.doneLabel,
        );
        if (encouragement.isNotEmpty) parts.add(encouragement);
        return MasterGreetingResult(parts.join(' '));
    }
  }

  /// 핵심 일정을 시작했는지 묻는 말. 슬롯 인사와 달리 [MasterGreetingContext]를
  /// 거치지 않는다 — 발화 조건(몇 시인지, 얼마나 밀렸는지)은 화면이 판단하고,
  /// 여기서는 이름만 받아 문장으로 옮긴다.
  String buildCoreAsk(String taskName) => _fill(voice.coreAsk, taskName);

  /// 되는 날에 무엇이 달랐는지 묻는 말.
  ///
  /// 지난 이레보다 해낸 날이 늘었으면 그 이야기부터 꺼낸다.
  String buildConditionAsk({int? from, int? to}) {
    if (from == null || to == null || to <= from) {
      return pickLine(voice.conditionAsk);
    }
    return pickLine(
      voice.conditionAskImproved
          .map(
            (line) =>
                line.replaceAll('{{from}}', '$from').replaceAll('{{to}}', '$to'),
          )
          .toList(growable: false),
    );
  }

  /// 답을 골랐을 때의 대꾸.
  String buildConditionReply() => pickLine(voice.conditionReply);

  /// 오늘 쓸 수 있는 시간을 묻는 말.
  String buildCapacityAsk() => pickLine(voice.capacityAsk);

  /// 답을 골랐을 때의 대꾸. 짧은 날과 여유 있는 날에 할 말이 다르다.
  String buildCapacityReply(String answer) => pickLine(
    answer == '온종일 비어 있어' || answer == '반나절쯤 돼'
        ? voice.capacityReplyRoomy
        : voice.capacityReplyTight,
  );

  /// 무엇이 시작을 막는지 묻는 말.
  String buildBlockerAsk() => pickLine(voice.blockerAsk);

  /// 목록에 없다고 했을 때, 적어달라고 청하는 말.
  String buildBlockerFreeAsk() => pickLine(voice.blockerFreeAsk);

  /// 무엇이 막는지 골랐을 때의 대꾸.
  String buildBlockerReply() => pickLine(voice.blockerReply);

  /// 목록에 없는 답이라고 했을 때, 적어달라고 청하는 말.
  String buildConditionFreeAsk() => pickLine(voice.conditionFreeAsk);

  /// 권한 대로 해내고 온 날의 인사.
  String buildAdviceWorked(String taskName, String advice) => pickLine(
    voice.adviceWorked
        .map(
          (line) => line
              .replaceAll('{{task}}', '\'$taskName\'')
              .replaceAll('{{advice}}', advice),
        )
        .toList(growable: false),
  );

  /// 며칠째 넘어온 일을 묻는 말.
  String buildCarriedAsk(String taskName, int days) => pickLine(
    voice.carriedAsk
        .map(
          (line) => line
              .replaceAll('{{task}}', '\'$taskName\'')
              .replaceAll('{{days}}', '$days'),
        )
        .toList(growable: false),
  );

  /// 지정해둔 것은 없지만 오늘 목록에 남아 있는 일을 묻는 말.
  String buildRepeatingAsk(String taskName) =>
      _fill(voice.repeatingAsk, taskName);

  /// 시작해두고 완료가 안 된 일을 물어보는 말.
  String buildStalledAsk(String taskName) => _fill(voice.stalledAsk, taskName);

  /// 지금 하고 있는 일을 인정하는 말.
  ///
  /// [nextTaskName]이 있으면 끝난 뒤 볼 것으로 하나만 남긴다. 없으면 인정만
  /// 하고 끝낸다 — 남길 것이 없는데 억지로 붙이면 아무 일이나 집게 된다.
  /// [spentLabel]이 있으면 시간을 말하는 문구도 후보에 넣는다. 없으면 기본
  /// 문구만 쓴다 — 짧게 붙잡고 있을 때는 시간을 말하지 않는 편이 낫다.
  String buildInProgressAck(
    String taskName,
    String? nextTaskName, {
    String? spentLabel,
  }) {
    final pool = <String>[
      ...(nextTaskName == null ? voice.inProgressAckOnly : voice.inProgressAck),
      if (spentLabel != null)
        ...(nextTaskName == null
            ? voice.inProgressAckSpentOnly
            : voice.inProgressAckSpent),
    ];
    return pickLine(
      pool
          .map(
            (line) => line
                .replaceAll('{{task}}', '\'$taskName\'')
                .replaceAll('{{next}}', '\'${nextTaskName ?? ''}\'')
                .replaceAll('{{spent}}', spentLabel ?? ''),
          )
          .toList(growable: false),
    );
  }

  String _fill(List<String> pool, String taskName) => pickLine(
    pool
        .map((line) => line.replaceAll('{{task}}', '\'$taskName\''))
        .toList(growable: false),
  );

  /// 곧 시작할 일정을 짚는 말. 시각은 앱이 붙인 것이라 묶지 않고,
  /// 일 이름은 사용자가 적은 말이라 따옴표로 묶는다.
  String _fillUpcoming(MasterGreetingContext context) => pickLine(
    voice.upcomingPlan
        .map(
          (line) => line
              .replaceAll('{{time}}', context.upcomingPlanTimeLabel ?? '')
              .replaceAll('{{task}}', '\'${context.upcomingPlanName ?? ''}\''),
        )
        .toList(growable: false),
  );

  /// 일 이름과 달리 시간대는 따옴표로 묶지 않는다. 사용자가 적은 말이 아니라
  /// 앱이 계산해 붙인 이름이라, 묶으면 인용처럼 보인다.
  String _fillWindow(List<String> pool, String windowLabel) => pickLine(
    pool
        .map((line) => line.replaceAll('{{window}}', windowLabel))
        .toList(growable: false),
  );

  /// 격려 문구. 완료한 일 이름이 있으면 문장 안에 녹이고, 없으면 이름 없는 형태를 쓴다.
  String pickEncouragement(List<(String, String)> pool, String? doneLabel) {
    if (pool.isEmpty) return '';
    final variants = pool
        .map(
          (pair) => doneLabel == null
              ? pair.$2
              : pair.$1.replaceAll('{{task}}', doneLabel),
        )
        .toList(growable: false);
    return pickLine(variants);
  }

  /// 미완료 일정은 3개까지만 버튼으로 세우고, 넘치면 '그 외'로 접는다.
  List<String> eveningChoices(List<String> pending) {
    if (pending.isEmpty) return const [];
    if (pending.length <= MasterGreetingCopy.pendingChoiceLimit) {
      return List<String>.unmodifiable(pending);
    }
    return List<String>.unmodifiable([
      ...pending.take(MasterGreetingCopy.pendingChoiceLimit),
      voice.otherChoiceLabel,
    ]);
  }

  /// 9시 이후 낮 발화. 상황과 질문을 각각 한 문장씩 두면 둘이 같은 말을 하게
  /// 되므로(계획 문구가 "막히면 말씀해 주세요"인데 뒤에 "필요하면 말씀해
  /// 주세요"가 또 붙었다) 한 문장만 낸다. 짚을 완료가 있으면 그게 할 말이고,
  /// 없으면 상황 문구를 쓴다 — 상황 문구가 제안까지 안에 품고 있다.
  String _dayLine(MasterGreetingContext context) {
    final encouragement = _dayEncouragement(context);
    if (encouragement.isNotEmpty) return encouragement;
    if (context.now.hour < 12) {
      return pickLine(
        context.hasPlan ? voice.morningPlan : voice.morningNoPlan,
      );
    }
    return pickLine(
      context.hasPlan ? voice.afternoonBehind : voice.afternoonNoPlan,
    );
  }

  /// 오전·오후 격려. 완료가 있으면 시각과 무관하게 붙는다.
  /// 기준은 완료율이 아니라 개수다 — 자동 주입된 습관이 분모를 오염시키기 때문.
  String _dayEncouragement(MasterGreetingContext context) {
    if (context.doneCount == 0) return '';
    if (context.now.hour < 12) {
      return pickEncouragement(
        context.doneCount >= 3 ? voice.encStrong : voice.encStarted,
        context.doneLabel,
      );
    }
    // 오후에 일정을 하나라도 끝냈으면 완료율과 무관하게 흐름 쪽으로 말한다.
    // 절반을 기준으로 갈라봐야 1/4쯤에서 "벌써 시작하셨네요"가 나가 어색했다.
    if (context.hasPlan && context.planDone > 0) {
      return pickEncouragement(voice.encFlow, context.doneLabel);
    }
    return pickEncouragement(voice.encStarted, context.doneLabel);
  }
}

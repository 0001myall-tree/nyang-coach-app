  static bool canAccessCoach(String id) {
    if (id == 'random') return true;
    final coach = all[CoachIdService.normalize(id)];
    if (coach == null) return false;
    if (coach.tier == 'master') {
      return false; // 잠금 처리
    }
    return true; // 기본 캐릭터
  }

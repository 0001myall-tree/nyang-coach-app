  /// 지금 시각에 해당하는 생활 루틴 지침만 뽑아 붙인다.
  ///
  /// 오후 2~6시는 원래도 규칙이 없던 구간이라 빈 문자열을 준다. 기상 루틴과
  /// 점심 챙기기가 겹치던 오전 10~12시는 점심 쪽으로 몰았다. 두 지시를 같이
  /// 실으면 어느 쪽을 따를지가 그날 운이 된다.
  static String lifeRoutineSection(CoachConfig coach, DateTime now) {
    final rules = coach.lifeRoutineByTimeOfDay;
    if (rules == null) return '';
    final hour = now.hour;
    final key = hour < 11
        ? 'morning'
        : hour < 14
        ? 'lunch'
        : hour < 18
        ? null
        : hour < 21
        ? 'evening'
        : 'night';
    final rule = key == null ? null : rules[key];
    if (rule == null) return '';
    return '''

[지금 시간대의 생활 루틴 개입]
대화 시작 시, 혹은 사용자가 "오늘 뭐부터 해?", "할 일 골라줘" 등 행동 제안을 요청할 때 참고한다. 단, 한 대화에서 밥/잠 언급은 1번만 하고 매번 똑같이 반복하지 않는다.
- $rule''';
  }


  final List<String> flirtHalf;
  final List<String> flirtFew;
  final List<String> flirtAll;
  final List<String> flirtCore;
  final String systemPrompt;

  /// 취침 예정 시각 무렵에만 프롬프트에 붙이는 규칙.
  ///
  /// 하루에 있을까 말까 한 상황인데 [systemPrompt] 안에 두면 매 요청마다 실려
  /// 나간다. 앱이 취침 시각을 이미 알고 있으니 그때만 붙인다. 프롬프트가 길고
  /// 안 쓰이는 지시가 섞일수록 모델이 정작 중요한 지시를 흘린다.
  final String? bedtimeCarryOverRule;

  /// 청소·정리 얘기가 오갈 때만 붙이는 코치별 노하우.
  /// 청소가 특기인 코치는 이 대목이 길어서, 늘 실으면 밥·잠 얘기를 할 때도
  /// 청소 팁이 프롬프트의 절반을 차지한다.
  final String? cleaningPlaybook;

  /// 코치가 아는 청소 조각들. [cleaningPlaybook]에서 떼어냈다.
  ///
  /// 규칙은 한 줄도 없이 이름만 있다. 무엇을 고를지는 여기서 가져오고, 어떻게
  /// 할지는 공통 실행 저항 개입이 정한다.
  ///
  /// 원래는 노하우와 한 덩어리였고 규칙도 섞여 있었다. "전체를 한 번에 하지
  /// 마라"는 [범위 좁히기]와, "오늘은 15분만"은 [시간 낮추기]와 같은 말이었다.
  /// 개입은 한 턴에 하나만 고르게 되어 있는데, 그 줄들이 어느 개입이 뽑히든
  /// 딸려 들어가서 원칙이 샜다.
  ///
  /// 붙는 자리는 한 군데뿐이다. 개입이 행동을 고르는 턴. 거기서는 개입이 준
  /// 예시 하나("물건 하나 치우기")를 이겨야 해서 이 이름들이 필요하다.
  ///
  /// 그냥 청소 얘기를 하는 턴에는 붙이지 않는다. 이길 예시가 없는 자리에
  /// 이름만 놓으면, 코치가 아는 것을 말하지 못하고 그 안에서만 고르게 된다.
  ///
  /// 여덟 줄을 통째로 주지 않고 앱이 한 줄만 골라 넘긴다. 다 주고 고르라고
  /// 하면 모델이 매번 비슷한 걸 집는다 — 개입 로테이션에서 이미 겪은 일이다.
  final List<CleaningFragment>? cleaningFragments;

  /// 코치가 아는 운동 조각의 이름들. [cleaningFragments]와 같은 자리에
  /// 같은 이유로 붙는다 — 개입이 행동을 고르는 턴에만.
  ///
  /// 공통 개입 [범위 좁히기]가 드는 예시는 청소·설거지·글쓰기·공부뿐이라 운동이
  /// 없다. 정작 이 코치에게 하기 싫다고 말하는 일의 대부분이 운동인데, 참고할
  /// 것이 없어 매번 새로 지어내야 했다.
  ///
  /// 이름 옆의 짧은 효용은 규칙이 아니라 코치가 아는 사실로 둔다. "효용도 같이
  /// 말해라"를 규칙으로 넣으면 [목적 연결] 개입과 같은 말이 되어, 어느 개입이
  /// 뽑히든 답이 "작은 행동 → 그러면 나아짐"으로 닫힌다. 청소 쪽에서 한 번
  /// 걷어낸 적이 있는 모양이다.
  final String? workoutSmallStepPlaybook;

  /// 운동 얘기가 오갈 때만 붙이는 코치별 운동 지침.
  ///
  /// 원래 운동 코치의 [systemPrompt] 안에 있었다. 그래서 무슨 얘기를 하든
  /// 따라다녔고, 맥락과 상관없이 스트레칭부터 하자는 말이 튀어나왔다.
  /// [cleaningPlaybook]과 같은 이유로 밖으로 뺀다.
  final String? workoutPlaybook;

  /// 시간대별 생활 루틴 지침. 키는 morning/lunch/evening/night.
  ///
  /// 네 구간을 통째로 실으면 지금과 무관한 지시가 셋이나 따라 나온다. 앱이
  /// 지금 몇 시인지 이미 아니까 해당 구간 하나만 붙인다. [bedtimeCarryOverRule]과
  /// 같은 이유다.
  final Map<String, String>? lifeRoutineByTimeOfDay;

  /// 알람 목소리 파일 개수 (0이면 기본 알림음 사용)
  /// 파일명 규칙: assets/voice/{id}_1.mp3, {id}_2.mp3, ...
  /// 나중에 목소리 추가 시 이 숫자만 올리면 자동 반영됨
  final int voiceCount;

  const CoachConfig({
    required this.id,
    required String name,
    required this.tier,
    required this.accentColor,
    required this.accentLight,
    required this.chips,
    this.flirtOne = const [],
    this.flirtHalf = const [],
    this.flirtFew = const [],
    this.flirtAll = const [],
    this.flirtCore = const [],
    required this.systemPrompt,
    this.bedtimeCarryOverRule,
    this.cleaningPlaybook,
    this.cleaningFragments,
    this.workoutSmallStepPlaybook,
    this.workoutPlaybook,
    this.lifeRoutineByTimeOfDay,
    this.voiceCount = 0,
    // ignore: prefer_initializing_formals
  }) : _name = name;

  String get name => _name;

  bool get isMaster => tier == 'master';
  String get imagePath => 'assets/images/$id.png';
  String get bgImagePath => 'assets/images/bg_$id.png';
}


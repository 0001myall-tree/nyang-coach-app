class CoachConfig {
  final String id;
  final String _name;
  final String tier;
  final Color accentColor;
  final Color accentLight;
  final List<String> chips;
  final List<String> flirtOne;
  final List<String> flirtHalf;
  final List<String> flirtFew;
  final List<String> flirtAll;
  final List<String> flirtCore;
  final String systemPrompt;

  /// 취침 예정 시각 무렵에만 프롬프트에 붙이는 규칙.
  ///
  /// 하루에 있을까 말까 한 상황인데 [systemPrompt] 안에 두면 매 요청마다 실려
  /// 나간다. 앱이 취침 시각을 이미 알고 있으니 그때만 붙인다. 프롬프트가 길고
  /// 안 쓰이는 지시가 섞일수록 모델이 정작 중요한 지시를 흘린다.
  final String? bedtimeCarryOverRule;

  /// 청소·정리 얘기가 오갈 때만 붙이는 코치별 노하우.
  /// 청소가 특기인 코치는 이 대목이 길어서, 늘 실으면 밥·잠 얘기를 할 때도
  /// 청소 팁이 프롬프트의 절반을 차지한다.
  final String? cleaningPlaybook;

  /// 시간대별 생활 루틴 지침. 키는 morning/lunch/evening/night.
  ///
  /// 네 구간을 통째로 실으면 지금과 무관한 지시가 셋이나 따라 나온다. 앱이
  /// 지금 몇 시인지 이미 아니까 해당 구간 하나만 붙인다. [bedtimeCarryOverRule]과
  /// 같은 이유다.
  final Map<String, String>? lifeRoutineByTimeOfDay;

  /// 알람 목소리 파일 개수 (0이면 기본 알림음 사용)
  /// 파일명 규칙: assets/voice/{id}_1.mp3, {id}_2.mp3, ...
  /// 나중에 목소리 추가 시 이 숫자만 올리면 자동 반영됨
  final int voiceCount;

  const CoachConfig({
    required this.id,
    required String name,
    required this.tier,
    required this.accentColor,
    required this.accentLight,
    required this.chips,
    this.flirtOne = const [],
    this.flirtHalf = const [],
    this.flirtFew = const [],
    this.flirtAll = const [],
    this.flirtCore = const [],
    required this.systemPrompt,
    this.bedtimeCarryOverRule,
    this.cleaningPlaybook,
    this.lifeRoutineByTimeOfDay,
    this.voiceCount = 0,
    // ignore: prefer_initializing_formals
  }) : _name = name;

  String get name => _name;

  bool get isMaster => tier == 'master';
  String get imagePath => 'assets/images/$id.png';
  String get bgImagePath => 'assets/images/bg_$id.png';
}

